#!/usr/bin/env python3
"""Board setup for an iBlack/iErmu camera (Hi3518EV100 + AR0141) after its move to OpenIPC.

Run it once after the migration and again after every factory reset (the reset wipes the overlay, where all of
this lives; the U-Boot env survives it). It builds one POSIX sh script and feeds it to the camera's shell:

    python3 easy/post_setup.py --ssh 'ssh root@CAMERA' --check   # report only; exit 1 if something would change
    python3 easy/post_setup.py --ssh 'ssh root@CAMERA'           # apply
    python3 easy/post_setup.py --ssh 'ssh root@CAMERA' --reboot  # apply, then reboot if a change needs it
    python3 easy/post_setup.py --print > post_setup.sh           # only write the script

--ssh takes any command that runs its last argument as a shell command on the camera with our stdin (ssh does).

What the script puts in place; every step is skipped when it is already right, so running it again is harmless:
  /usr/sbin/sysupgrade            the update guard (update/sysupgrade-guard.sh); the original stays in /rom
  env upgrade                     an unreachable URL, so an unguarded online update cannot fetch anything
  /etc/modules + wdt module       the vendor U-Boot leaves the hardware watchdog running; wdt.ko keeps it fed
  env sensor=ar0141               lets load_hisilicon finish, which also loads wdt.ko
  /etc/sensors/ar0141_i2c_720p.ini  the 720p sensor setup (video/)
  /etc/majestic.yaml              isp.blkCnt=9, the night mode pins (night/) and the speaker amplifier pin
                                  audio.speakerPin=63 (audio/); a missing file gets night/majestic.yaml, an
                                  existing one only the keys that differ, and the day/night thresholds only
                                  where they are not set (yours are kept)
  /etc/init.d/S94lightsensor      light sensor -> majestic's ADC readout (night/)
  /etc/init.d/S96vicheck          restarts majestic when the VI gets no frames after a cold start (video/)
  /usr/lib/libmajaudiofix.so      makes majestic encode the microphone as mono (without it Opus and AAC
                                  carry half of the sound, an octave too high) and applies
                                  audio.outputVolume to the speaker (audio/)
  /etc/init.d/S95majestic         preloads that library and runs the firmware's script from /rom (audio/);
                                  both are left out when S95majestic is neither the firmware's nor ours
The env steps only fill in unset variables; a different value is reported and left alone.

The script stops before changing anything unless /proc/mtd shows the fixed slots of a migrated camera, the
original updater is at /rom/usr/sbin/sysupgrade and fw_printenv can read the env. It never writes U-Boot, the
kernel, the rootfs or the Wi-Fi settings, and never runs the updater. Changes to the sensor, majestic.yaml, the
init scripts or the audio fix take effect after a reboot.

Exit status (also of --ssh): 0 done or nothing to do, 1 --check found something to change, 2 error,
3 the --ssh command itself failed.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import shlex
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = HERE.parent
sys.path.insert(0, str(BASE))
from make_env import DEFAULT_SENSOR, NO_ONLINE_UPDATE_URL  # noqa: E402

VERSION = 3
# (payload name, source in this directory tree)
PAYLOADS = (("guard", BASE / "update" / "sysupgrade-guard.sh"),
            ("sensor_ini", BASE / "video" / "ar0141_i2c_720p.ini"),
            ("majestic_yaml", BASE / "night" / "majestic.yaml"),
            ("s94", BASE / "night" / "S94lightsensor"),
            ("s96", BASE / "video" / "S96vicheck"),
            ("audiofix", BASE / "audio" / "libmajaudiofix.so"),
            ("s95", BASE / "audio" / "S95majestic"))
# majestic.yaml keys that describe the board; set whenever they differ.
BOARD_KEYS = ((".isp.blkCnt", "9"), (".nightMode.lightMonitor", "true"), (".nightMode.irCutSingleInvert", "true"),
              (".nightMode.irCutPin1", "2"), (".nightMode.backlightPin", "52"),
              (".nightMode.adcReadout", "true"), (".nightMode.adcInvert", "true"), (".audio.speakerPin", "63"))
# majestic.yaml keys the owner may tune; set only where missing.
DEFAULT_KEYS = ((".nightMode.minThreshold", "100"), (".nightMode.maxThreshold", "150"))
EOF_MARK = "__POST_SETUP_PAYLOAD__"

TEMPLATE = r'''#!/bin/sh
# post_setup @VERSION@ for an iBlack/iErmu camera on OpenIPC (fixed slots of the vendor U-Boot).
# Generated by easy/post_setup.py; see there. Touches only overlay files and the env variables sensor/upgrade.
MODE=@MODE@
REBOOT_AFTER=@REBOOT@
R=${POST_SETUP_ROOT:-}
SENSOR=@SENSOR@
NO_UPDATE_URL='@URL@'
MIN_FREE_KB=64
changed=0 pending=0 failed=0 reboot=0 space_ok=

say() { echo "post_setup: $*"; }
die() {
	say "error: $*"
	exit 2
}
already() { say "already: $1"; }
note() { say "note: $1"; }
fail() {
	say "failed: $1"
	failed=$((failed + 1))
}
# done_ ITEM [reboot]: one step changed (or, with --check, would change) something
done_() {
	if [ "$MODE" = check ]; then
		say "would change: $1"
		pending=$((pending + 1))
	else
		say "changed: $1"
		changed=$((changed + 1))
	fi
	[ -z "$2" ] || reboot=1
}

layout_ok() {
	[ -r "$R/proc/mtd" ] || return 1
	awk '
		$4 == "\"boot\"" { b = $1 $2 }
		$4 == "\"env\"" { e = $1 $2 }
		$4 == "\"kernel\"" { k = $1 $2 }
		$4 == "\"rootfs\"" { r = $1 $2 }
		$4 == "\"rootfs_data\"" { d = $1 $2 }
		END {
			ok = b == "mtd0:00060000" && e == "mtd1:00010000" && k == "mtd2:001d0000" &&
				r == "mtd3:004e0000" && d == "mtd4:000e0000"
			exit !ok
		}' "$R/proc/mtd"
}

for c in awk base64 cli cmp cut df fw_printenv fw_setenv grep md5sum mktemp tail; do
	command -v "$c" >/dev/null 2>&1 || die "'$c' not found; nothing was changed"
done
layout_ok || die "/proc/mtd does not show the fixed slots of a migrated iBlack (boot 384K, env 64K, kernel 1856K," \
	"rootfs 4992K, rootfs_data 896K); nothing was changed"
[ -f "$R/rom/usr/sbin/sysupgrade" ] || die "/rom/usr/sbin/sysupgrade is missing; nothing was changed"
fw_printenv >/dev/null 2>&1 || die "fw_printenv cannot read the U-Boot env; nothing was changed"
T=$(mktemp -d "${TMPDIR:-/tmp}/post_setup.XXXXXX") || die "mktemp failed; nothing was changed"
trap 'rm -rf "$T"' EXIT
trap 'exit 2' HUP INT TERM

# unpack NAME MD5 < base64: payloads are checked before anything is changed
unpack() {
	base64 -d >"$T/$1" || die "cannot unpack $1; nothing was changed"
	[ "$(md5sum <"$T/$1" | cut -d' ' -f1)" = "$2" ] || die "$1 arrived damaged; nothing was changed"
}
@PAYLOADS@

# install SRC DEST MODE: write a temporary file next to DEST, then rename it over DEST
install_file() {
	if [ -z "$space_ok" ]; then
		free=$(df -k "$R/etc/" 2>/dev/null | awk 'END { print $(NF - 2) }')
		case $free in
		'' | *[!0-9]*) die "cannot read the free space of the overlay" ;;
		esac
		[ "$free" -ge "$MIN_FREE_KB" ] || die "only ${free}K free in the overlay, ${MIN_FREE_KB}K needed"
		space_ok=1
	fi
	mkdir -p "${2%/*}" &&
		cp "$1" "$2.post_setup" && chmod "$3" "$2.post_setup" && mv -f "$2.post_setup" "$2" && return 0
	rm -f "$2.post_setup"
	fail "cannot write ${2#"$R"}"
	return 1
}

# put ITEM SRC DEST MODE [reboot]
put() {
	if [ -f "$R$3" ] && cmp -s "$2" "$R$3"; then
		if [ "$4" = 755 ] && [ ! -x "$R$3" ]; then
			[ "$MODE" = check ] || chmod 755 "$R$3" || {
				fail "cannot chmod $3"
				return
			}
			done_ "$1 (made executable)" "$5"
		else
			already "$1"
		fi
		return
	fi
	[ "$MODE" = check ] || install_file "$2" "$R$3" "$4" || return
	done_ "$1" "$5"
}

# env_fill VAR VALUE [reboot]: set VAR only if it is unset
env_fill() {
	cur=$(fw_printenv -n "$1" 2>/dev/null)
	if [ "$cur" = "$2" ]; then
		already "env $1"
	elif [ -n "$cur" ]; then
		note "env $1 is '$cur', not '$2'; left as is"
	else
		if [ "$MODE" != check ]; then
			fw_setenv "$1" "$2" || {
				fail "fw_setenv $1"
				return
			}
			[ "$(fw_printenv -n "$1" 2>/dev/null)" = "$2" ] || {
				fail "env $1 did not read back as '$2'"
				return
			}
		fi
		done_ "env $1=$2" "$3"
	fi
}

# 1. update guard, and the env URL that keeps an unguarded online update from fetching anything
put "/usr/sbin/sysupgrade (update guard)" "$T/guard" /usr/sbin/sysupgrade 755
if cmp -s "$T/guard" "$R/usr/sbin/sysupgrade"; then
	[ -z "$R" ] || export SYSUPGRADE_GUARD_PROC_MTD="$R/proc/mtd" SYSUPGRADE_GUARD_REAL="$R/rom/usr/sbin/sysupgrade"
	st=$(sh "$R/usr/sbin/sysupgrade" --guard-status 2>&1)
	case $st in
	*"flash layout: fixed slots"*) ;;
	*) fail "the installed guard does not report the fixed slots" ;;
	esac
	case $st in
	*"updater version: known"*) ;;
	*) note "the guard has not reviewed the updater in /rom and refuses every write until it is updated" ;;
	esac
fi
env_fill upgrade "$NO_UPDATE_URL"

# 2. watchdog
M=$R/etc/modules
if [ -f "$M" ] && grep -qE '^wdt( |$)' "$M"; then
	already "/etc/modules: wdt"
else
	: >"$T/modules"
	[ -f "$M" ] && cat "$M" >"$T/modules"
	[ -s "$T/modules" ] && [ -n "$(tail -c 1 "$T/modules")" ] && echo >>"$T/modules"
	echo wdt >>"$T/modules"
	if [ "$MODE" = check ] || install_file "$T/modules" "$M" 644; then
		done_ "/etc/modules: wdt"
	fi
fi
if grep -q '^wdt ' "$R/proc/modules" 2>/dev/null; then
	already "wdt module loaded"
elif [ "$MODE" = check ] || modprobe wdt; then
	done_ "wdt module loaded"
else
	fail "modprobe wdt"
fi

# 3. sensor and video
env_fill sensor "$SENSOR" reboot
put /etc/sensors/ar0141_i2c_720p.ini "$T/sensor_ini" /etc/sensors/ar0141_i2c_720p.ini 644 reboot

# 4. majestic.yaml: board keys always, thresholds only where unset
Y=$R/etc/majestic.yaml
if [ ! -f "$Y" ]; then
	if [ "$MODE" = check ] || install_file "$T/majestic_yaml" "$Y" 600; then
		done_ "/etc/majestic.yaml (new, from night/majestic.yaml)" reboot
	fi
elif cp "$Y" "$T/cur.yaml"; then
	keys= ok=1
	for kv in @BOARD_KEYS@; do
		k=${kv%%=*} v=${kv#*=}
		[ "$(cli -i "$T/cur.yaml" -g "$k" 2>/dev/null)" = "$v" ] && continue
		cli -i "$T/cur.yaml" -o "$T/cur.yaml" -s "$k" "$v" >/dev/null 2>&1 || ok=
		keys="$keys ${k#.}=$v"
	done
	for kv in @DEFAULT_KEYS@; do
		k=${kv%%=*} v=${kv#*=}
		cli -i "$T/cur.yaml" -g "$k" >/dev/null 2>&1 && continue
		cli -i "$T/cur.yaml" -o "$T/cur.yaml" -s "$k" "$v" >/dev/null 2>&1 || ok=
		keys="$keys ${k#.}=$v"
	done
	if [ -z "$ok" ]; then
		fail "cli could not edit a copy of /etc/majestic.yaml; the file was left as is"
	elif [ -z "$keys" ]; then
		already "/etc/majestic.yaml"
	elif [ "$MODE" = check ] || install_file "$T/cur.yaml" "$Y" 600; then
		done_ "/etc/majestic.yaml:$keys" reboot
	fi
else
	fail "cannot read /etc/majestic.yaml"
fi

# 5. init scripts
put /etc/init.d/S94lightsensor "$T/s94" /etc/init.d/S94lightsensor 755 reboot
put /etc/init.d/S96vicheck "$T/s96" /etc/init.d/S96vicheck 755 reboot

# 6. audio: the fix library, and the S95majestic that preloads it; only over the firmware's S95majestic
#    or one of ours (an older one of ours mentions the library)
S95=$R/etc/init.d/S95majestic
if [ ! -f "$R/rom/etc/init.d/S95majestic" ] || [ ! -f "$S95" ]; then
	note "/etc/init.d/S95majestic or the firmware's copy in /rom is missing; left as is (no audio fix)"
elif cmp -s "$S95" "$R/rom/etc/init.d/S95majestic" || grep -q libmajaudiofix "$S95"; then
	put /usr/lib/libmajaudiofix.so "$T/audiofix" /usr/lib/libmajaudiofix.so 644 reboot
	put "/etc/init.d/S95majestic (audio fix)" "$T/s95" /etc/init.d/S95majestic 755 reboot
else
	note "/etc/init.d/S95majestic is not the firmware's; left as is (no audio fix)"
fi

[ "$changed" -eq 0 ] || sync
if [ "$failed" -gt 0 ]; then
	say "result: $changed changed, $failed failed; fix the cause and run post_setup again"
	exit 2
fi
if [ "$MODE" = check ]; then
	if [ "$pending" -eq 0 ]; then
		say "result: nothing to change"
		exit 0
	fi
	if [ "$reboot" -eq 1 ]; then
		say "result: $pending would change, then a reboot"
	else
		say "result: $pending would change, no reboot needed"
	fi
	exit 1
fi
if [ "$changed" -eq 0 ]; then
	say "result: nothing to change"
elif [ "$reboot" -eq 0 ]; then
	say "result: $changed changed, no reboot needed"
elif [ "$REBOOT_AFTER" = 1 ]; then
	say "result: $changed changed, rebooting now"
	reboot
else
	say "result: $changed changed, reboot the camera to use them"
fi
exit 0
'''


def _keys(pairs) -> str:
    return " ".join(f"{k}={v}" for k, v in pairs)


def _payload(name: str, data: bytes) -> str:
    b64 = base64.encodebytes(data).decode("ascii")
    return f"unpack {name} {hashlib.md5(data).hexdigest()} <<'{EOF_MARK}'\n{b64}{EOF_MARK}"


def build_script(mode: str = "apply", reboot: bool = False, payloads=None) -> str:
    """The camera script. mode: "apply" or "check"; reboot: reboot at the end if a change needs it."""
    if mode not in ("apply", "check"):
        raise ValueError(f"mode must be apply or check, not {mode!r}")
    if reboot and mode == "check":
        raise ValueError("--reboot does not go with --check")
    for value in (DEFAULT_SENSOR, NO_ONLINE_UPDATE_URL):
        if not value or any(c in value for c in " '\"\\$`\n"):
            raise ValueError(f"unsafe value {value!r}")
    if payloads is None:
        payloads = [(name, path.read_bytes()) for name, path in PAYLOADS]
    text = TEMPLATE
    for key, value in (("@VERSION@", str(VERSION)), ("@MODE@", mode), ("@REBOOT@", "1" if reboot else "0"),
                       ("@SENSOR@", DEFAULT_SENSOR), ("@URL@", NO_ONLINE_UPDATE_URL),
                       ("@BOARD_KEYS@", _keys(BOARD_KEYS)), ("@DEFAULT_KEYS@", _keys(DEFAULT_KEYS)),
                       ("@PAYLOADS@", "\n".join(_payload(n, d) for n, d in payloads))):
        assert text.count(key) == 1, key
        text = text.replace(key, value)
    return text


def run_remote(command: str, script: str, timeout: float) -> int:
    """Feeds the script to COMMAND + ["sh -s"] and passes its output on. The exit status is the script's, or 3
    when the script did not get to its last line (connection, login or timeout)."""
    argv = shlex.split(command) + ["sh -s"]
    try:
        p = subprocess.Popen(argv, stdin=subprocess.PIPE, stdout=subprocess.PIPE)
        try:
            out, _ = p.communicate(script.encode(), timeout=timeout)
        except subprocess.TimeoutExpired:
            p.kill()
            out, _ = p.communicate()
            sys.stdout.write(out.decode(errors="replace"))
            print(f"post_setup: --ssh command did not finish within {timeout:g} s", file=sys.stderr)
            return 3
    except OSError as e:
        print(f"post_setup: --ssh command failed: {e}", file=sys.stderr)
        return 3
    text = out.decode(errors="replace")
    sys.stdout.write(text)
    last = [line for line in text.splitlines() if line.startswith(("post_setup: result:", "post_setup: error:"))]
    if last and last[-1].endswith("rebooting now"):
        return 0  # the connection may drop before the script's own exit status arrives
    if not last or p.returncode not in (0, 1, 2):
        print(f"post_setup: the script did not finish (--ssh exit status {p.returncode}; connection or login "
              "problem?)", file=sys.stderr)
        return 3
    return p.returncode


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    how = ap.add_mutually_exclusive_group(required=True)
    how.add_argument("--ssh", metavar="CMD", help="command that runs a shell command on the camera, e.g. 'ssh root@IP'")
    how.add_argument("--print", action="store_true", help="write the camera script to stdout")
    ap.add_argument("--check", action="store_true", help="change nothing; exit 1 if something would change")
    ap.add_argument("--reboot", action="store_true", help="reboot the camera at the end if a change needs it")
    ap.add_argument("--timeout", type=float, default=180, help="seconds for --ssh (default %(default)s)")
    a = ap.parse_args(argv)
    if a.check and a.reboot:
        ap.error("--reboot does not go with --check")
    script = build_script("check" if a.check else "apply", a.reboot)
    if a.print:
        sys.stdout.write(script)
        return 0
    return run_remote(a.ssh, script, a.timeout)


if __name__ == "__main__":
    sys.exit(main())
